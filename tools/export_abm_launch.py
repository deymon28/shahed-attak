"""Export launch anchors from the same geometry and camera as the ABM sprites."""
import hashlib
import json
from pathlib import Path
import sys

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / 'tools'))
import bpy
from bpy_extras.object_utils import world_to_camera_view
from mathutils import Vector
import hybrid_defenses as model
import hybrid_renderer as renderer
from hybrid_manifest import fingerprint


def main():
    scene = renderer.setup()
    result = model.build('abm')
    scene.camera.data.ortho_scale = result['ortho_scale']
    scene.render.resolution_x = scene.render.resolution_y = 576
    # Runtime frame width 192 px, scale .65, 32 pixels per tile.
    units = 192 * .65 / 32
    def project(point):
        uv = world_to_camera_view(scene, scene.camera, point)
        return [(uv.x - .5) * units, (.5 - uv.y) * units]
    frames = []
    for direction in range(64):
        positions = []
        for phase in range(9):
            model.animate('abm', direction, phase, 'launch', result)
            transform = result['movers']['rocket'].matrix_world
            # The midpoint between the model's tail and nose keeps the flight
            # sprite center aligned with the visible rocket, not its empty root.
            center = transform @ (Vector(result['launch_axis']) * .1025)
            positions.append(project(center))
        axis = transform.to_3x3() @ Vector(result['launch_axis'])
        front, back = project(center + axis * .4125), project(center - axis * .4125)
        dx, dy = front[0] - back[0], front[1] - back[1]
        length = (dx * dx + dy * dy) ** .5
        # The retained flight sprite's visible body is 120 px at scale .5.
        frames.append({'positions': positions, 'direction': [dx / length, dy / length],
                       'scale': length / (120 * .5 / 32)})
    output = ROOT / 'scripts/lib/abm_launch_geometry.lua'
    lines = ['-- Generated by tools/export_abm_launch.py; offsets are in Factorio tiles.', 'return {']
    for index, frame in enumerate(frames):
        points = ', '.join('{x=%.9f,y=%.9f}' % tuple(p) for p in frame['positions'])
        dx, dy = frame['direction']
        lines.append('  [%d] = {positions={%s}, direction={x=%.9f,y=%.9f}, scale=%.9f},' %
                     (index, points, dx, dy, frame['scale']))
    lines.append('}')
    output.write_text('\n'.join(lines) + '\n', encoding='utf-8')
    metadata = {'source_digest': fingerprint('abm'),
                'exporter_sha256': hashlib.sha256(Path(__file__).read_bytes()).hexdigest(),
                'runtime_sha256': hashlib.sha256(output.read_bytes()).hexdigest(), 'directions': frames}
    (ROOT / 'graphics/renders/abm-launch-anchors.json').write_text(json.dumps(metadata, indent=2))
    print('PASS: exported all 64 ABM launch directions from the sprite geometry', flush=True)


if __name__ == '__main__':
    main()
